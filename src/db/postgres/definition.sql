-- Read only; resolve the identifier as data, never interpolate it into SQL.
SELECT CASE
WHEN c.relkind IN ('v','m') THEN
    E'-- Structure preview; ownership, grants, comments and view options are not included.\n' ||
    'CREATE ' || CASE WHEN c.relkind = 'm' THEN 'MATERIALIZED ' ELSE '' END ||
    'VIEW ' || pg_catalog.format('%I.%I', n.nspname, c.relname) || E' AS\n' || pg_catalog.rtrim(pg_catalog.pg_get_viewdef(c.oid, true), ';') ||
    CASE WHEN c.relkind = 'm' THEN E'\nWITH NO DATA;' ELSE ';' END
WHEN c.relkind = 'r' AND NOT c.relispartition
    AND NOT EXISTS (SELECT 1 FROM pg_catalog.pg_inherits WHERE inhrelid=c.oid) THEN
    E'-- Structure preview; ownership, grants, comments, policies and sequence settings are not included.\n' ||
    'CREATE ' || CASE c.relpersistence WHEN 'u' THEN 'UNLOGGED ' WHEN 't' THEN 'TEMPORARY ' ELSE '' END ||
    'TABLE ' || pg_catalog.format('%I.%I', n.nspname, c.relname) || E' (\n' ||
    COALESCE((SELECT pg_catalog.string_agg('    ' || definition, E',\n' ORDER BY position, definition) FROM (
        SELECT a.attnum::integer AS position,
            pg_catalog.format('%I %s', a.attname, pg_catalog.format_type(a.atttypid,a.atttypmod)) ||
            CASE WHEN a.attcollation <> 0 AND a.attcollation <> t.typcollation
                THEN ' COLLATE ' || (SELECT pg_catalog.format('%I.%I', cn.nspname, co.collname)
                    FROM pg_catalog.pg_collation co JOIN pg_catalog.pg_namespace cn ON cn.oid=co.collnamespace WHERE co.oid=a.attcollation)
                ELSE '' END ||
            CASE WHEN a.attidentity='a' THEN ' GENERATED ALWAYS AS IDENTITY'
                 WHEN a.attidentity='d' THEN ' GENERATED BY DEFAULT AS IDENTITY'
                 WHEN a.attgenerated<>'' THEN ' GENERATED ALWAYS AS (' || pg_catalog.pg_get_expr(d.adbin,d.adrelid) || ')' || CASE WHEN a.attgenerated='v' THEN ' VIRTUAL' ELSE ' STORED' END
                 WHEN d.adbin IS NOT NULL THEN ' DEFAULT ' || pg_catalog.pg_get_expr(d.adbin,d.adrelid)
                 ELSE '' END ||
            CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END AS definition
        FROM pg_catalog.pg_attribute a JOIN pg_catalog.pg_type t ON t.oid=a.atttypid
        LEFT JOIN pg_catalog.pg_attrdef d ON d.adrelid=a.attrelid AND d.adnum=a.attnum
        WHERE a.attrelid=c.oid AND a.attnum>0 AND NOT a.attisdropped
        UNION ALL
        SELECT 32768, 'CONSTRAINT ' || pg_catalog.quote_ident(conname) || ' ' || pg_catalog.pg_get_constraintdef(oid, true)
        FROM pg_catalog.pg_constraint WHERE conrelid=c.oid AND contype IN ('p','u','f','c','x')
    ) definitions), '') || E'\n);' ||
    COALESCE((SELECT E'\n\n' || pg_catalog.string_agg(pg_catalog.pg_get_indexdef(i.indexrelid) || ';', E'\n' ORDER BY i.indexrelid)
        FROM pg_catalog.pg_index i WHERE i.indrelid=c.oid AND NOT EXISTS
            (SELECT 1 FROM pg_catalog.pg_constraint k WHERE k.conindid=i.indexrelid AND k.contype IN ('p','u','x'))), '') ||
    COALESCE((SELECT E'\n\n' || pg_catalog.string_agg(pg_catalog.pg_get_triggerdef(t.oid, true) || ';', E'\n' ORDER BY t.tgname)
        FROM pg_catalog.pg_trigger t WHERE t.tgrelid=c.oid AND NOT t.tgisinternal), '')
END
FROM pg_catalog.pg_class c JOIN pg_catalog.pg_namespace n ON n.oid=c.relnamespace
WHERE c.oid=pg_catalog.to_regclass($1)
