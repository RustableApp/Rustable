#!/usr/bin/env python3
"""Generate an offline completion grammar from the attributed Redis metadata."""
import json
from pathlib import Path
root = Path(__file__).resolve().parent.parent
commands = json.loads((root/'assets/redis/commands.json').read_text())
# Rustable-authored module syntax; intentionally separate from upstream metadata.
modules = {
 'JSON.GET': 'key [path...]', 'JSON.SET': 'key path value [NX|XX]',
 'JSON.DEL': 'key [path]', 'JSON.TYPE': 'key [path]', 'JSON.ARRAPPEND': 'key path value...',
 'JSON.ARRLEN': 'key [path]', 'JSON.OBJKEYS': 'key [path]', 'JSON.NUMINCRBY': 'key path increment',
 'FT._LIST': '', 'FT.INFO': 'index', 'FT.SEARCH': 'index query [NOCONTENT] [WITHSCORES] [LIMIT offset count] [DIALECT dialect]',
 'FT.AGGREGATE': 'index query [GROUPBY count property...] [LIMIT offset count] [DIALECT dialect]',
 'FT.PROFILE': 'index SEARCH|AGGREGATE [LIMITED] QUERY query',
 'FT.EXPLAIN': 'index query [DIALECT dialect]', 'FT.DROPINDEX': 'index [DD]',
 'FT.CREATE': 'index [ON HASH|JSON] [PREFIX count prefix...] SCHEMA field TEXT|TAG|NUMERIC|GEO|VECTOR',
 'TS.GET': 'key [LATEST]', 'TS.INFO': 'key [DEBUG]', 'TS.RANGE': 'key fromTimestamp toTimestamp [LATEST] [COUNT count]',
 'TS.REVRANGE': 'key fromTimestamp toTimestamp [COUNT count]', 'TS.ADD': 'key timestamp value',
 'TS.CREATE': 'key [RETENTION retention]', 'TS.DEL': 'key fromTimestamp toTimestamp',
 'VCARD': 'key', 'VDIM': 'key', 'VINFO': 'key', 'VEMB': 'key element [RAW]',
 'VGETATTR': 'key element', 'VSETATTR': 'key element json', 'VREM': 'key element',
 'VRANDMEMBER': 'key [count]', 'VISMEMBER': 'key element',
 'VADD': 'key VALUES count value... element', 'VSIM': 'key ELE element [COUNT count] [WITHSCORES]',
 'VLINKS': 'key element [WITHSCORES]',
}
import re
def module_args(s):
 out=[]
 for part in re.findall(r'\[[^]]+\]|\S+',s):
  optional=part.startswith('['); part=part.strip('[]')
  parts=part.split()
  if len(parts)>1: a={'type':'block','arguments':module_args(part),'name':'option'}
  elif '|' in part: a={'type':'oneof','arguments':[{'name':p,'type':'pure-token','token':p} for p in part.split('|')],'name':'option'}
  elif part.isupper(): a={'type':'pure-token','token':part,'name':part}
  else: a={'type':'key' if part=='key' else 'string','name':part.removesuffix('...'),'multiple':part.endswith('...')}
  a['optional']=optional;out.append(a)
 return out
for name,syntax in modules.items():
 commands[name]={'summary': 'Redis module command; requires compatible server support.', 'since':'module','group':name.split('.')[0].lower(), 'arguments':module_args(syntax)}
def q(s): return json.dumps(s,ensure_ascii=False)
output=['// Generated by scripts/generate-redis-completions.py. See assets/redis/README.md.', 'use super::{Command, Edge};','pub(super) static COMMANDS: &[Command] = &[']
for name,c in sorted(commands.items()):
 edges=[];n=1; next_slot=1
 def state():
  global n
  v=n;n+=1;return v
 def edge(a,b,label='',kind='value',slot=0): edges.append((a,b,label,kind,slot))
 def literal_first(a):
  if a.get('token'): return True
  children=a.get('arguments',[])
  if a['type']=='oneof': return bool(children) and all(literal_first(x) for x in children)
  if a['type']=='block': return bool(children) and literal_first(children[0])
  return False
 def sequence(args,start,end,slot=0):
  global next_slot
  if not args: edge(start,end);return
  for i,arg in enumerate(args):
   tail=args[i:]
   if slot==0 and all(a.get('optional') and literal_first(a) for a in tail):
    edge(start,end)
    for a in tail:
     group=0 if a.get('multiple') else next_slot; next_slot+=1
     compile_arg(dict(a,optional=False),start,start,group)
    return
   target=end if i==len(args)-1 else state(); compile_arg(arg,start,target,slot);start=target
 def compile_arg(a,start,end,slot=0):
  enter=state();leave=state();edge(start,enter);edge(leave,end)
  if a.get('optional'): edge(start,end)
  if a.get('multiple'): edge(leave,enter)
  if a.get('token'):
   dest=leave if a['type']=='pure-token' else state();edge(enter,dest,a['token'],'token',slot);enter=dest
  if a['type']=='pure-token': return
  if a['type']=='oneof':
   for child in a.get('arguments',[]): compile_arg(child,enter,leave,slot)
  elif a['type']=='block': sequence(a.get('arguments',[]),enter,leave,slot)
  else: edge(enter,leave,a.get('display_text',a['name']),a['type'])
 def syntax(a):
  if a['type']=='pure-token': s=a.get('token',a['name'])
  elif a['type']=='oneof': s=' | '.join(syntax(x) for x in a.get('arguments',[]))
  elif a['type']=='block': s=' '.join(syntax(x) for x in a.get('arguments',[]))
  else: s=(a.get('token','')+' '+a.get('display_text',a['name'])).strip()
  if a.get('multiple'): s+=' …'
  return '['+s+']' if a.get('optional') else s
 end=state(); sequence(c.get('arguments',[]),0,end)
 sig=name+' '+ ' '.join(syntax(a) for a in c.get('arguments',[]))
 output.append(f'Command {{ name: {q(name)}, summary: {q(c.get("summary",""))}, signature: {q(sig.strip())}, group: {q(c.get("group",""))}, since: {q(c.get("since",""))}, edges: &[')
 for a,b,label,kind,slot in edges: output.append(f'Edge {{ from: {a}, to: {b}, label: {q(label)}, kind: {q(kind)}, slot: {slot} }},')
 output.append(']},')
output.append('];')
(root/'src/redis_completion_catalog.rs').write_text('\n'.join(output)+'\n')
print(len(commands),'commands generated')
